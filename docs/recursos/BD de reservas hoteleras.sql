CREATE TABLE IF NOT EXISTS HUESPED (
    ID_HUESPED          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE              VARCHAR2(50) NOT NULL,
    APELLIDO            VARCHAR2(50) NOT NULL,
    EMAIL               VARCHAR2(150) NOT NULL,
    TELEFONO            VARCHAR2(10) NOT NULL,
    TIPO_DOCUMENTO      VARCHAR2(50) NOT NULL,
    NUMERO_DOCUMENTO    VARCHAR2(20) NOT NULL,
    NACIONALIDAD        VARCHAR2(50) NOT NULL,
    ESTADO_REGISTRO     VARCHAR2(30) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT HUESPED_PK PRIMARY KEY (ID_HUESPED), 
    CONSTRAINT HUESPED_TELEFONO_CHK CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{10}$')),
    CONSTRAINT HUESPED_TIPO_DOC_CHK CHECK (TIPO_DOCUMENTO IN ('INE', 'LICENCIA', 'PASAPORTE')),
    CONSTRAINT HUESPED_ESTADO_REG_CHK CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

CREATE TABLE IF NOT EXISTS HABITACION (
    ID_HABITACION       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NUMERO              NUMBER(10) NOT NULL,
    TIPO                VARCHAR2(50) NOT NULL,
    PRECIO              NUMBER(10, 2) NOT NULL,
    CAPACIDAD           NUMBER(5) NOT NULL,
    ESTADO              VARCHAR2(30) DEFAULT 'DISPONIBLE' NOT NULL,
    ESTADO_REGISTRO     VARCHAR2(30) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT HABITACION_PK PRIMARY KEY (ID_HABITACION),
    CONSTRAINT HABITACION_NUMERO_CHK CHECK (NUMERO > 0),
    CONSTRAINT HABITACION_PRECIO_CHK CHECK (PRECIO > 0),
    CONSTRAINT HABITACION_CAPACIDAD_CHK CHECK (CAPACIDAD >= 1),
    CONSTRAINT HABITACION_TIPO_CHK CHECK (TIPO IN ('SENCILLA', 'DOBLE', 'SUITE')),
    CONSTRAINT HABITACION_ESTADO_CHK CHECK (ESTADO IN ('DISPONIBLE', 'OCUPADA', 'LIMPIEZA', 'MANTENIMIENTO')),
    CONSTRAINT HABITACION_ESTADO_REG_CHK CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

CREATE TABLE IF NOT EXISTS RESERVA (
    ID_RESERVA          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_HUESPED          NUMBER(10) NOT NULL,
    ID_HABITACION       NUMBER(10) NOT NULL,
    FECHA_ENTRADA       DATE NOT NULL,
    FECHA_SALIDA        DATE NOT NULL,
    NUMERO_PERSONAS     NUMBER(5) NOT NULL,
    PRECIO_NOCHE        NUMBER(10, 2) NOT NULL,
    PRECIO_TOTAL        NUMBER(10, 2) NOT NULL,
    ESTADO              VARCHAR2(30) DEFAULT 'CONFIRMADA' NOT NULL,
    ESTADO_REGISTRO     VARCHAR2(30) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT RESERVA_PK PRIMARY KEY (ID_RESERVA),
    CONSTRAINT RESERVA_FECHAS_CHK CHECK (FECHA_ENTRADA < FECHA_SALIDA),
    CONSTRAINT RESERVA_NUM_PERSONAS_CHK CHECK (NUMERO_PERSONAS >= 1),
    CONSTRAINT RESERVA_PRECIO_NOCHE_CHK CHECK (PRECIO_NOCHE >= 0),
    CONSTRAINT RESERVA_PRECIO_TOTAL_CHK CHECK (PRECIO_TOTAL >= 0),
    CONSTRAINT RESERVA_ESTADO_CHK CHECK (ESTADO IN ('CONFIRMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA')),
    CONSTRAINT RESERVA_ESTADO_REG_CHK CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

